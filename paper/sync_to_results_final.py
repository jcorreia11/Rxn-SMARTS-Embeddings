"""
Mirror paper/ outputs into results/final/4-paper/ for easy local browsing,
alongside every other experiment phase.

paper/*.json and paper/figures/* remain the git-tracked, backed-up record
(unchanged location, still generated by the individual paper/*_stats.py and
paper/plot_*.py scripts) — this just copies them into the same
results/final/ tree everything else lands in. results/final/ itself is
gitignored (a local convenience mirror), matching every other phase's
mirroring convention set up in the .sbatch scripts.

Run this after the individual paper/*.py scripts have produced their
outputs (typically after the HPC experiment scripts have finished and their
results/final/ mirrors are available locally).

Usage: python paper/sync_to_results_final.py
"""

import shutil
from pathlib import Path

PAPER_DIR = Path("paper")
MIRROR_DIR = Path("results/final/4-paper")


def main() -> None:
    MIRROR_DIR.mkdir(parents=True, exist_ok=True)

    json_files = sorted(PAPER_DIR.glob("*.json"))
    for src in json_files:
        shutil.copy2(src, MIRROR_DIR / src.name)
    print(f"Copied {len(json_files)} JSON file(s) -> {MIRROR_DIR}/")

    figures_src = PAPER_DIR / "figures"
    if figures_src.is_dir():
        figures_dst = MIRROR_DIR / "figures"
        figures_dst.mkdir(parents=True, exist_ok=True)
        fig_files = sorted(p for p in figures_src.iterdir() if p.is_file())
        for src in fig_files:
            shutil.copy2(src, figures_dst / src.name)
        print(f"Copied {len(fig_files)} figure file(s) -> {figures_dst}/")
    else:
        print(f"No {figures_src}/ directory found — skipping figures.")


if __name__ == "__main__":
    main()